"""
Regression tests for the LLM-based title extractor.

The fixture file tests/data/title_extraction_eval.json is generated by
    python -m cinescout.scripts.build_title_eval

Each entry looks like:
    {"raw": "Exhibition on Screen: Frida Kahlo 2026 Encore", "expected": "Frida Kahlo"}

The "expected" field is initially set to the model output and can be
hand-corrected.  These tests re-run the model and assert the output
matches "expected", so they serve as a regression guard against prompt
or model changes.

Because they hit a local Ollama instance they are marked @pytest.mark.live
and excluded from CI:
    pytest -m "not live"   # skips these
    pytest -m live         # runs only these
"""

import json
from pathlib import Path

import pytest

from cinescout.services.title_extractor import extract_film_title
from cinescout.utils.text import normalise_title

_EVAL_PATH = Path(__file__).resolve().parents[2] / "tests" / "data" / "title_extraction_eval.json"


def _load_cases() -> list[tuple[str, str]]:
    if not _EVAL_PATH.exists():
        return []
    data = json.loads(_EVAL_PATH.read_text())
    return [(entry["raw"], entry["expected"]) for entry in data]


@pytest.mark.live
@pytest.mark.parametrize("raw,expected", _load_cases(), ids=lambda x: x[:60] if isinstance(x, str) else x)
async def test_title_extraction(raw: str, expected: str) -> None:
    after_regex = normalise_title(raw)
    result = await extract_film_title(after_regex)
    assert result == expected, (
        f"Title extraction mismatch\n"
        f"  raw:      {raw!r}\n"
        f"  expected: {expected!r}\n"
        f"  got:      {result!r}"
    )
